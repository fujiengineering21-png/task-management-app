-- TaskBoard のテーブルを作る（docs/DB設計.md の 3章どおり）
-- このファイルは一度適用したら書き換えない。テーブルを変えるときは V2__… を新しく足す

-- ボード（「仕事」「プライベート」の2行だけ）
CREATE TABLE boards (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(20) NOT NULL UNIQUE,
    position   SMALLINT    NOT NULL UNIQUE,   -- タブの並び順（0＝左、1＝右）
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- タスク
CREATE TABLE tasks (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id     BIGINT        NOT NULL REFERENCES boards (id),
    status       VARCHAR(10)   NOT NULL DEFAULT 'todo'
                 CHECK (status IN ('todo', 'doing', 'done')),   -- どのカラムにあるか
    position     INTEGER       NOT NULL,                        -- カラム内の表示順（0 から）
    title        VARCHAR(100)  NOT NULL,
    description  VARCHAR(1000),                                 -- NULL＝説明なし
    is_completed BOOLEAN       NOT NULL DEFAULT false,
    priority     VARCHAR(10)
                 CHECK (priority IN ('high', 'medium', 'low')), -- NULL＝優先度なし
    due_date     DATE,                                          -- NULL＝期限なし
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ボードを開いたとき、カラムごとに順番どおり速く取り出すための索引
-- 並び替えの途中で順番が一時的に重なることがあるので、UNIQUE にはしない
CREATE INDEX idx_tasks_board_status_position ON tasks (board_id, status, position);

-- ラベル
CREATE TABLE labels (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id   BIGINT      NOT NULL REFERENCES boards (id),
    name       VARCHAR(20) NOT NULL DEFAULT '',   -- 名前なしは空の文字（NULL だと下の重複チェックが効かない）
    color      VARCHAR(10) NOT NULL
               CHECK (color IN ('green', 'yellow', 'orange', 'red', 'purple', 'blue')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (board_id, color, name)                -- 同じボードに、色も名前も同じラベルは作れない
);

-- タスクとラベルの結び付け（多対多）
-- タスクかラベルを削除すると、この行も一緒に消える
CREATE TABLE task_labels (
    task_id  BIGINT NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    label_id BIGINT NOT NULL REFERENCES labels (id) ON DELETE CASCADE,
    PRIMARY KEY (task_id, label_id)
);
